//! Scan-table SRCTYPE values and their MeasurementSet state metadata.

/// The state name and subscan number encoded by a scan-table SRCTYPE.
pub(super) fn state(source_type: i32) -> (&'static str, i32) {
    match source_type {
        0 => ("OBSERVE_TARGET#ON_SOURCE,POSITION_SWITCH", 1),
        1 => ("OBSERVE_TARGET#OFF_SOURCE,POSITION_SWITCH", 2),
        2 => ("OBSERVE_TARGET#ON_SOURCE,NOD", 1),
        3 => ("OBSERVE_TARGET#ON_SOURCE,FREQUENCY_SWITCH#SIG", 1),
        4 => ("OBSERVE_TARGET#ON_SOURCE,FREQUENCY_SWITCH#REF", 2),
        6 => ("CALIBRATE_ATMOSPHERE#OFF_SOURCE,UNSPECIFIED", 1),
        7 => ("CALIBRATE_ATMOSPHERE#HOT,UNSPECIFIED", 2),
        8 => ("CALIBRATE_ATMOSPHERE#WARM,UNSPECIFIED", 3),
        9 => ("CALIBRATE_ATMOSPHERE#COLD,UNSPECIFIED", 4),
        10 => ("CALIBRATE_ATMOSPHERE#ON_SOURCE,POSITION_SWITCH", 5),
        11 => ("CALIBRATE_ATMOSPHERE#OFF_SOURCE,POSITION_SWITCH", 6),
        12 => ("CALIBRATE_ATMOSPHERE#ON_SOURCE,NOD", 7),
        13 => ("CALIBRATE_ATMOSPHERE#ON_SOURCE,FREQUENCY_SWITCH#SIG", 8),
        14 => ("CALIBRATE_ATMOSPHERE#OFF_SOURCE,FREQUENCY_SWITCH#REF", 9),
        20 => ("OBSERVE_TARGET#ON_SOURCE,FREQUENCY_SWITCH#LOWER", 1),
        21 => ("OBSERVE_TARGET#OFF_SOURCE,FREQUENCY_SWITCH#LOWER", 2),
        26..=29 => (
            "CALIBRATE_ATMOSPHERE#OFF_SOURCE,FREQUENCY_SWITCH#LOWER",
            source_type - 25,
        ),
        30 => ("OBSERVE_TARGET#ON_SOURCE,FREQUENCY_SWITCH#HIGHER", 3),
        31 => ("OBSERVE_TARGET#OFF_SOURCE,FREQUENCY_SWITCH#HIGHER", 4),
        36..=39 => (
            "CALIBRATE_ATMOSPHERE#OFF_SOURCE,FREQUENCY_SWITCH#HIGHER",
            source_type - 31,
        ),
        90 => ("OBSERVE_TARGET#ON_SOURCE,UNSPECIFIED", 1),
        91 => ("OBSERVE_TARGET#OFF_SOURCE,UNSPECIFIED", 2),
        92 => ("CALIBRATE_SOMETHING#OFF_SOURCE,UNSPECIFIED", 1),
        _ => ("UNKNOWN_INTENT", 1),
    }
}
