/// Annual aberration velocity in units of light speed at a TDB MJD.
/// CASACORE's FK4 series uses Julian centuries from 1900 January 0.5.
pub(in crate::measures) fn velocity(mjd: f64) -> [f64; 3] {
    let t = (mjd - 15_019.5) / 36_525.0;
    let arguments =
        FUNDAMENTAL.map(|[a, b, c, d]| (a + t * (b + t * (c + t * d))) * super::ARCSEC_RAD);
    let mut value = [0.0; 3];
    for (i, (multipliers, coefficients)) in SERIES.iter().enumerate() {
        let phase: f64 = multipliers
            .iter()
            .zip(arguments)
            .map(|(&n, a)| f64::from(n) * a)
            .sum();
        let (sin, cos) = phase.sin_cos();
        let factor = match i {
            55 => t * t * t,
            44 => t * t,
            0 | 3 | 54 | 113 | 119 | 120 | 128 | 129 => t,
            _ => 1.0,
        };
        for (axis, component) in value.iter_mut().enumerate() {
            *component += factor
                * (f64::from(coefficients[2 * axis]) * sin
                    + f64::from(coefficients[2 * axis + 1]) * cos);
        }
    }
    const AU_PER_DAY_OVER_C: f64 = 149_597_870_659.0 / 86_400.0 / 299_792_458.0;
    value.map(|v| v * 1e-8 * AU_PER_DAY_OVER_C)
}

